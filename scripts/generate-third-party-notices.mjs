import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const npmCli = process.env.npm_execpath;
if (!npmCli) throw new Error('Run this script using npm run notices.');
const paths = execFileSync(process.execPath,
  [npmCli, 'ls', '--omit=dev', '--all', '--parseable'], { cwd: root, encoding: 'utf8' })
  .trim().split(/\r?\n/).filter(path => path !== root.replace(/[\\/]$/, ''));
const packages = [...new Set(paths)].map(path => ({
  path,
  metadata: JSON.parse(readFileSync(join(path, 'package.json'), 'utf8')),
})).sort((a, b) => a.metadata.name.localeCompare(b.metadata.name, 'en'));
let output = 'Third-party software notices\nGenerated by npm run notices from installed production dependencies.\n'
  + 'JSZip is used under its MIT license option. Other license options are reproduced as supplied.\n';
for (const { path, metadata } of packages) {
  const files = readdirSync(path).filter(name => /^(licen[sc]e|copying|notice)([.-].*)?$/i.test(name)).sort();
  if (!files.some(name => /^(licen[sc]e|copying)/i.test(name))) {
    // Some older packages (for example isarray) embed their full license in README.
    const readme = readdirSync(path).find(name => /^readme(\..*)?$/i.test(name));
    if (!readme || !/^#{1,6} licen[sc]e\s*$/im.test(readFileSync(join(path, readme), 'utf8'))) {
      throw new Error(`Missing license text for ${metadata.name}; review and preserve its license manually.`);
    }
    files.push(readme);
  }
  output += `\n${'='.repeat(72)}\n${metadata.name}@${metadata.version} (${metadata.license ?? 'see license below'})\n`;
  for (const name of files) {
    output += `\n--- ${name} ---\n${readFileSync(join(path, name), 'utf8').replace(/\r\n/g, '\n').trim()}\n`;
  }
}
const target = join(root, 'public/third-party-notices.txt');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    throw new Error('Third-party notices are stale. Run npm run notices and commit the result.');
  }
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, output);
}
console.log(`Third-party notices ${process.argv.includes('--check') ? 'verified' : 'generated'} for ${packages.length} packages.`);
